-- Preventa: pagos del cliente y comprobante.
-- Cada preventa puede tener un total (opcional) y varios pagos (seña, resto...).
-- Los pagos no se borran: si se cargó mal, se anula con motivo (queda en auditoría).
-- receipt_no: número correlativo para el comprobante que se le manda al cliente.

alter table preorders add column total_amount numeric(14,2) check (total_amount is null or total_amount >= 0);
alter table preorders add column receipt_no bigint generated by default as identity;
create unique index uq_preorders_receipt_no on preorders (receipt_no);

create table preorder_payments (
  id uuid primary key default gen_random_uuid(),
  preorder_id uuid not null references preorders(id) on delete restrict,
  paid_on date not null default current_date,
  amount numeric(14,2) not null check (amount > 0),
  method text not null check (method in ('TRANSFERENCIA', 'EFECTIVO', 'MERCADO_PAGO', 'OTRO')),
  notes text,
  created_by text,
  created_at timestamptz not null default now(),
  idempotency_key text unique,
  voided_at timestamptz,
  voided_by text,
  void_reason text,
  check ((voided_at is null) = (voided_by is null))
);
create index idx_preorder_payments_preorder on preorder_payments (preorder_id, paid_on);

alter table preorder_payments enable row level security;
